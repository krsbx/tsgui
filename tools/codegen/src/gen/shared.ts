/**
 * Backend dlopen-type name per FfiType — the single source for both defs
 * tables. Keyed by the model's FfiType, so adding a kind fails to
 * typecheck here instead of silently emitting `undefined` in one backend.
 *
 * `bun: "void"` is documentation only: bun:ffi has no FFIType.void, so the
 * defs-bun generator omits `returns` entirely for void functions.
 */
import type { FFITypeStringToType } from "bun:ffi";
import type { ReturnType as FFIReturnType } from "node:ffi";
import type { FfiType } from "../model";

/** Shared helper for generated-file headers. */
export function banner(origin: string): string[] {
  return [`// GENERATED by @tsgui/codegen from ${origin} — DO NOT EDIT.`, ``];
}

export const KIND_BACKEND_TYPES = {
  void: { bun: "void", node: "void" },
  bool: { bun: "bool", node: "bool" },
  i8: { bun: "i8", node: "int8" },
  u8: { bun: "u8", node: "uint8" },
  i16: { bun: "i16", node: "int16" },
  u16: { bun: "u16", node: "uint16" },
  i32: { bun: "i32", node: "int32" },
  u32: { bun: "u32", node: "uint32" },
  i64: { bun: "i64", node: "int64" },
  u64: { bun: "u64", node: "uint64" },
  f32: { bun: "f32", node: "float" },
  f64: { bun: "f64", node: "f64" },
  string: { bun: "cstring", node: "string" },
  pointer: { bun: "pointer", node: "pointer" },
} satisfies Record<
  FfiType,
  { bun: keyof FFITypeStringToType; node: FFIReturnType }
>;
