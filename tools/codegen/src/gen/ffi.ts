/**
 * FFI backend table generators.
 *
 * Emits three files per target library from one parsed header dump:
 *   - constants file   (enum constants — backend-agnostic)
 *   - bun:ffi defs     (declarative dlopen table)
 *   - node:ffi defs    (declarative dlopen table)
 *
 * The tables are data only; loading and pointer handling live in the
 * hand-written parts of @tsgui/bindings.
 */
import type { FfiTables } from '../model';
import type { FfiType } from '../model';

/** C kind → bun:ffi FFIType member. */
const BUN_TYPE: Record<string, string> = {
  void: 'void',
  bool: 'bool',
  i8: 'i8',
  u8: 'u8',
  i16: 'i16',
  u16: 'u16',
  i32: 'i32',
  u32: 'u32',
  i64: 'i64',
  u64: 'u64',
  f32: 'f32',
  f64: 'f64',
  string: 'cstring',
  pointer: 'pointer',
};

/** C kind → node:ffi type string. */
const NODE_TYPE: Record<string, string> = {
  void: 'void',
  bool: 'bool',
  i8: 'int8',
  u8: 'uint8',
  i16: 'int16',
  u16: 'uint16',
  i32: 'int32',
  u32: 'uint32',
  i64: 'int64',
  u64: 'uint64',
  f32: 'float32',
  f64: 'float64',
  string: 'string',
  pointer: 'pointer',
};

function banner(origin: string): string[] {
  return [
    `// GENERATED by @tsgui/codegen from ${origin} — DO NOT EDIT.`,
    ``,
  ];
}

export function generateFfiConstants(
  tables: FfiTables,
  origin: string,
  defines: { name: string; value: number }[] = [],
  definesExportName = 'Defines'
): string {
  const L = banner(origin);
  L.push(`/** Enum constants from ${origin}. */`);
  for (const e of tables.enums) {
    L.push(`export const ${e.tsName} = {`);
    for (const c of e.constants) {
      L.push(`  ${c.name}: ${c.value},`);
    }
    L.push(`} as const;`);
    L.push(``);
  }

  if (defines.length > 0) {
    L.push(`/** Numeric #define constants (invisible to the AST). */`);
    L.push(`export const ${definesExportName} = {`);
    for (const d of defines) {
      L.push(`  ${d.name}: ${d.value},`);
    }
    L.push(`} as const;`);
    L.push(``);
  }
  return L.join('\n');
}

export function generateBunDefs(
  tables: FfiTables,
  origin: string,
  defsExportName: string
): string {
  const L = banner(origin);
  L.push(`import { FFIType } from "bun:ffi";`);
  L.push(``);
  L.push(`/** bun:ffi dlopen table for ${origin}. */`);
  L.push(`export const ${defsExportName} = {`);
  for (const fn of tables.functions) {
    const args =
      fn.args.length === 0
        ? `[]`
        : `[${fn.args.map((a) => `FFIType.${BUN_TYPE[a.kind]}`).join(', ')}]`;
    L.push(
      `  ${fn.name}: { args: ${args}, returns: FFIType.${BUN_TYPE[fn.returns]} },`
    );
  }
  L.push(`} as const;`);
  L.push(``);
  return L.join('\n');
}

export function generateNodeDefs(
  tables: FfiTables,
  origin: string,
  defsExportName: string
): string {
  const L = banner(origin);
  L.push(`/** node:ffi dlopen table for ${origin} (Node >= 26.9). */`);
  L.push(`export const ${defsExportName} = {`);
  for (const fn of tables.functions) {
    const args =
      fn.args.length === 0
        ? `[]`
        : `[${fn.args.map((a) => JSON.stringify(NODE_TYPE[a.kind])).join(', ')}]`;
    L.push(`  ${fn.name}: { arguments: ${args}, return: ${JSON.stringify(NODE_TYPE[fn.returns])} },`);
  }
  L.push(`} as const;`);
  L.push(``);
  return L.join('\n');
}

/* ------------------------------------------------------------------ */
/* Typed symbol surface + single-object-param wrappers                 */
/* ------------------------------------------------------------------ */

/** TS type for one FfiType — shared by the symbols and functions surfaces. */
function tsType(kind: FfiType, position: 'param' | 'return'): string {
  switch (kind) {
    case 'void':
      return position === 'return' ? 'void' : 'never';
    case 'bool':
      return 'boolean';
    case 'i64':
    case 'u64':
      // 64-bit ints cross FFI as bigint.
      return position === 'param' ? 'number | bigint' : 'bigint';
    case 'i8':
    case 'u8':
    case 'i16':
    case 'u16':
    case 'i32':
    case 'u32':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      // C char* is nullable unless documented otherwise — SDL's
      // SDL_CreateRenderer(w, null)-style default-arg patterns rely on it.
      return position === 'param' ? 'string | null' : 'string';
    case 'pointer':
      // Opaque handles and borrowed buffers; backend-shaped values flow
      // function → function without inspection.
      return 'unknown';
  }
}

function generateSymbolsType(tables: FfiTables, pascalName: string): string {
  const L = banner(`symbols type for ${pascalName}`);
  L.push(`/** Raw positional surface of the loaded ${pascalName} library. */`);
  L.push(`export interface ${pascalName}Symbols {`);
  for (const fn of tables.functions) {
    const args = fn.args
      .map((a) => `${a.name}: ${tsType(a.kind, 'param')}`)
      .join(', ');
    L.push(`  ${fn.name}(${args}): ${tsType(fn.returns, 'return')};`);
  }
  L.push(`}`);
  L.push(``);
  return L.join('\n');
}

function generateFunctions(tables: FfiTables, pascalName: string): string {
  const L = banner(`single-object-param wrappers for ${pascalName}`);
  L.push(`import type { ${pascalName}Symbols } from "./types.ts";`);
  L.push(`export type { ${pascalName}Symbols } from "./types.ts";`);
  L.push(``);
  L.push(`/**`);
  L.push(` * Object-param surface over the raw symbols — the toolkit convention`);
  L.push(` * (docs/ARCHITECTURE.md). One options object per call; no-arg`);
  L.push(` * functions stay no-arg.`);
  L.push(` */`);
  L.push(`export interface ${pascalName}Functions {`);
  for (const fn of tables.functions) {
    if (fn.args.length === 0) {
      L.push(`  ${fn.name}(): ${tsType(fn.returns, 'return')};`);
      continue;
    }
    const fields = fn.args
      .map((a) => `${a.name}: ${tsType(a.kind, 'param')}`)
      .join('; ');
    L.push(`  ${fn.name}(opts: { ${fields} }): ${tsType(fn.returns, 'return')};`);
  }
  L.push(`}`);
  L.push(``);
  L.push(
    `export function create${pascalName}Functions(symbols: ${pascalName}Symbols): ${pascalName}Functions {`
  );
  L.push(`  return {`);
  for (const fn of tables.functions) {
    if (fn.args.length === 0) {
      L.push(`    ${fn.name}: () => symbols.${fn.name}(),`);
      continue;
    }
    const positional = fn.args.map((a) => `opts.${a.name}`).join(', ');
    L.push(`    ${fn.name}: (opts) => symbols.${fn.name}(${positional}),`);
  }
  L.push(`  };`);
  L.push(`}`);
  L.push(``);
  return L.join('\n');
}

export function generateTypesAndFunctions(
  tables: FfiTables,
  pascalName: string
): { types: string; functions: string } {
  return {
    types: generateSymbolsType(tables, pascalName),
    functions: generateFunctions(tables, pascalName),
  };
}

/** Used by the CLI report so missing capabilities are visible, not silent. */
export function summarizeUnsafe(tables: FfiTables, limit = 20): string {
  if (tables.unsafe.length === 0) return '';
  const samples = tables.unsafe
    .slice(0, limit)
    .map((u) => `  ${u.name}: ${u.reason}`)
    .join('\n');
  const more =
    tables.unsafe.length > limit
      ? `\n  … and ${tables.unsafe.length - limit} more`
      : '';
  return `\nFFI-unsafe (excluded): ${tables.unsafe.length}\n${samples}${more}`;
}
